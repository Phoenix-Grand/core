/// A fresh primary key, generated by the process rather than by the database.
///
/// Kubuno's tables declare `DEFAULT gen_random_uuid()`, which neither MySQL nor
/// SQLite has and which - more importantly - makes the new key unknowable
/// without `RETURNING`. **Every insert that needs its key back must generate it
/// here and bind it explicitly.**
#[inline]
pub fn new_id() -> uuid::Uuid {
    uuid::Uuid::new_v4()
}
